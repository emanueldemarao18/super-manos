async page => {
  const base = 'http://127.0.0.1:8767/super-manos/';
  const context = await page.context().browser().newContext({viewport:{width:844,height:390},isMobile:true,hasTouch:true,deviceScaleFactor:2,userAgent:'Mozilla/5.0 (iPhone; CPU iPhone OS 18_0 like Mac OS X) AppleWebKit/605.1.15 Version/18.0 Mobile/15E148 Safari/604.1'});
  await context.addInitScript(()=>document.addEventListener('DOMContentLoaded',()=>{if(window.SM?.Audio&&!SM.Audio.muted)SM.Audio.toggleMute();},{once:true}));
  const phone = await context.newPage(), errors=[];
  phone.on('pageerror', error=>errors.push(error.message));
  await phone.request.post('http://127.0.0.1:8767/__release?version=1');
  await phone.goto(base);
  await phone.waitForFunction(()=>navigator.serviceWorker.controller,null,{timeout:20000});
  const manifest = await phone.evaluate(async()=>await (await fetch('manifest.webmanifest')).json());
  if(manifest.display!=='standalone'||manifest.scope!=='./'||!manifest.icons.some(i=>i.sizes==='512x512'))throw Error('Invalid install manifest');
  await phone.locator('#pwa-open').click();
  if(!await phone.locator('#pwa-install-help').textContent().then(t=>t.includes('Partilhar')))throw Error('iPhone installation instructions missing');
  await phone.locator('#pwa-save').click();
  await phone.waitForFunction(()=>document.querySelector('#pwa-save').textContent==='PRONTO PARA JOGAR OFFLINE',null,{timeout:60000});
  await phone.screenshot({path:'/private/tmp/manos-pwa-panel.png'});
  const saved = await phone.evaluate(async()=>{
    const cache=await caches.open('super-manos:/super-manos/:art-1');return (await cache.keys()).length;
  });
  if(saved!==25)throw Error('Incomplete offline art pack: '+saved);
  await context.setOffline(true);
  await phone.reload();
  await phone.waitForFunction(()=>window.SM?.App);
  await phone.evaluate(()=>document.fonts.ready);
  const fonts=await phone.evaluate(()=>document.fonts.check('16px "Bangers"')&&document.fonts.check('16px "Russo One"'));
  if(!fonts)throw Error('Game fonts unavailable offline');
  await phone.touchscreen.tap(420,190);
  await phone.waitForFunction(()=>SM.Touch.active);
  await phone.evaluate(()=>{SM.App.S.mode='training';SM.App.S.picked=[11,1];SM.App.S.stageSel=0;SM.App.S.screen='fightNow';});
  await phone.waitForFunction(()=>SM.App.S.battle?.phase==='fight'&&SM.Art.combatReady('rodrigo')&&SM.Art.combatReady('leonardo'));
  await phone.evaluate(()=>{const fs=SM.App.S.battle.fighters;fs[0].x=320;fs[1].x=360;});
  const hp=await phone.evaluate(()=>SM.App.S.battle.fighters[1].hp);
  await phone.locator('[data-b="hp"]').tap();
  await phone.waitForTimeout(700);
  const damage=hp-await phone.evaluate(()=>SM.App.S.battle.fighters[1].hp);
  if(damage<=0)throw Error('Offline touch combat failed');
  if(await phone.locator('#pwa-open').isVisible())throw Error('Installation UI overlaps combat');
  await phone.screenshot({path:'/private/tmp/manos-pwa-offline.png'});
  await context.setOffline(false);
  await phone.request.post('http://127.0.0.1:8767/__release?version=2');
  await phone.evaluate(async()=>await (await navigator.serviceWorker.getRegistration()).update());
  await phone.waitForFunction(async()=>!!(await navigator.serviceWorker.getRegistration()).waiting);
  if(await phone.locator('#pwa-open').isVisible())throw Error('Update interrupted a fight');
  const versionBefore=await phone.evaluate(async()=> (await caches.keys()).filter(k=>k.includes('pwa-test-')));
  if(!versionBefore.some(k=>k.endsWith('pwa-test-1')))throw Error('Running release discarded before update consent');
  await phone.evaluate(()=>{SM.App.S.screen='menu';SM.App.S.mode=null;SM.App.S.battle=null;});
  const other=await context.newPage();await other.goto(base);
  await phone.locator('#pwa-open').click();await phone.locator('#pwa-update').click();
  await phone.waitForFunction(()=>document.querySelector('#pwa-status').textContent.includes('outras janelas'));
  await other.close();
  const sentinel=await phone.evaluate(async()=>{await caches.open('unrelated-app-cache');return true;});
  await phone.locator('#pwa-update').click();
  await phone.waitForFunction(()=>!document.querySelector('#pwa-panel')?.open);
  await phone.waitForFunction(async()=> (await caches.keys()).includes('super-manos:/super-manos/:pwa-test-2'));
  await phone.locator('#pwa-open').click();
  await phone.waitForFunction(()=>document.querySelector('#pwa-save').textContent==='PRONTO PARA JOGAR OFFLINE');
  const finalCaches=await phone.evaluate(()=>caches.keys());
  if(finalCaches.includes('super-manos:/super-manos/:pwa-test-1')||!finalCaches.includes('unrelated-app-cache'))throw Error('Unsafe cache cleanup');
  if(errors.length)throw Error(errors.join('\n'));
  await context.close();
  return {installMetadata:true,iphoneHelp:true,offlineAssets:saved,offlineRodrigoDamage:damage,subpath:true,updateWaitedDuringFight:true,multipleWindowGuard:true,artPreservedAfterUpdate:true,unrelatedCachePreserved:sentinel,pageErrors:errors};
}
