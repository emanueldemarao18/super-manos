'use strict';
// Run with node tools/gameplay-test.cjs. Real game logic, with browser/audio boundaries stubbed.
const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const listeners = {};
const listen = (name, fn) => (listeners[name] ||= []).push(fn);
const emit = (name, props = {}) => (listeners[name] || []).forEach(fn => fn({ preventDefault() {}, ...props }));
const ctx = vm.createContext({ console, Math, Set, URLSearchParams, setTimeout,
  window: {}, document: { hidden: false, addEventListener: listen },
  navigator: {}, location: { search: '' }, addEventListener: listen });
const load = name => vm.runInContext(fs.readFileSync(path.join(__dirname, '../src', name + '.js'), 'utf8'), ctx);
load('config');
const SM = ctx.window.SM;
SM.Audio = { init() {}, sfx() {}, music() {} };
SM.Net = {};
SM.UI = {};
SM.Stages = { list: [{ id: 'test' }] };
for (const name of ['input', 'rig', 'characters', 'moves', 'fx', 'fighter', 'battle', 'ai', 'app']) load(name);
const S = SM.App.S, B = SM.BTN;
const tap = code => { emit('keydown', { code }); SM.App.update(); emit('keyup', { code }); SM.App.update(); };
Object.assign(S, { mode: 'cpu', picked: [0, 1], screen: 'fightNow' });
SM.App.update();
assert.equal(S.screen, 'fight');
tap('Enter');
assert.equal(S.paused, true);
tap('ArrowDown'); tap('Enter');
assert.equal(S.showMoves, true, 'Enter opens selected move list');
tap('Escape');
assert.equal(S.showMoves, false);
assert.equal(S.paused, true, 'Back from moves stays paused');
tap('Escape');
assert.equal(S.paused, false);
emit('keydown', { code: 'KeyD' });
emit('blur');
SM.App.update();
assert.equal(S.paused, true, 'Leaving offline battle pauses');
assert.equal(SM.Input.held(0), 0, 'Blur clears pending input');
const frozen = S.battle.t;
for (let i = 0; i < 60; i++) SM.App.update();
assert.equal(S.battle.t, frozen, 'Paused fight does not advance');
S.mode = 'online'; S.paused = false;
emit('blur');
assert.equal(S.paused, false, 'Online fight is not locally paused');
S.mode = 'cpu';
ctx.document.hidden = true; emit('visibilitychange');
assert.equal(S.paused, true, 'Hidden offline battle pauses');
console.log('gameplay OK: pause navigation, focus, input clearing, online exclusion');
