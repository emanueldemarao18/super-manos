'use strict';
// Run with node tools/gameplay-test.cjs. Real game logic, with browser/audio boundaries stubbed.
const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const listeners = {};
const listen = (name, fn) => (listeners[name] ||= []).push(fn);
const emit = (name, props = {}) => (listeners[name] || []).forEach(fn => fn({ preventDefault() {}, ...props }));
const ctx = vm.createContext({ console, Math, Set, URLSearchParams, setTimeout,
  window: {}, document: { hidden: false, addEventListener: listen },
  navigator: {}, location: { search: '' }, addEventListener: listen });
const load = name => vm.runInContext(fs.readFileSync(path.join(__dirname, '../src', name + '.js'), 'utf8'), ctx);
load('config');
const SM = ctx.window.SM;
SM.Audio = { init() {}, sfx() {}, music() {} };
SM.Net = {};
SM.UI = {};
SM.Stages = { list: [{ id: 'test' }] };
for (const name of ['input', 'rig', 'characters', 'moves', 'fx', 'fighter', 'battle', 'ai', 'app']) load(name);
const S = SM.App.S, B = SM.BTN;
const tap = code => { emit('keydown', { code }); SM.App.update(); emit('keyup', { code }); SM.App.update(); };
Object.assign(S, { mode: 'cpu', picked: [0, 1], screen: 'fightNow' });
SM.App.update();
assert.equal(S.screen, 'fight');
tap('Enter');
assert.equal(S.paused, true);
tap('ArrowDown'); tap('Enter');
assert.equal(S.showMoves, true, 'Enter opens selected move list');
tap('Escape');
assert.equal(S.showMoves, false);
assert.equal(S.paused, true, 'Back from moves stays paused');
tap('Escape');
assert.equal(S.paused, false);
emit('keydown', { code: 'KeyD' });
emit('blur');
SM.App.update();
assert.equal(S.paused, true, 'Leaving offline battle pauses');
assert.equal(SM.Input.held(0), 0, 'Blur clears pending input');
const frozen = S.battle.t;
for (let i = 0; i < 60; i++) SM.App.update();
assert.equal(S.battle.t, frozen, 'Paused fight does not advance');
S.mode = 'online'; S.paused = false;
emit('blur');
assert.equal(S.paused, false, 'Online fight is not locally paused');
S.mode = 'cpu';
ctx.document.hidden = true; emit('visibilitychange');
assert.equal(S.paused, true, 'Hidden offline battle pauses');
console.log('gameplay OK: pause navigation, focus, input clearing, online exclusion');

Object.assign(S, { mode: 'training', picked: [0, 1], screen: 'fightNow' });
SM.App.update();
const bt = S.battle, [att, def] = bt.fighters;
bt.phase = 'fight';
// Pause actions remain reachable with the same controls as every other menu.
tap('Enter'); tap('ArrowDown'); tap('ArrowDown'); tap('ArrowDown'); tap('Enter');
assert.equal(bt.trainingGuard, 1);
assert.equal(S.paused, true);
att.x = def.x - 45; att.state = 'attack';
let input = bt.controllers[1].read(bt, def);
def.input(input.held, input.pressed);
assert.equal(bt.wouldBlock(def, att, 'high'), true);
assert.equal(bt.wouldBlock(def, att, 'low'), false);
tap('Enter');
assert.equal(bt.trainingGuard, 2);
input = bt.controllers[1].read(bt, def); def.input(input.held, input.pressed);
assert.equal(bt.wouldBlock(def, att, 'low'), true);
assert.equal(bt.wouldBlock(def, att, 'overhead'), false);
att.x = def.x + 45;
input = bt.controllers[1].read(bt, def); def.input(input.held, input.pressed);
assert.equal(bt.wouldBlock(def, att, 'low'), true, 'Guard follows crossed-up opponent');
att.state = 'stand';
const dummyX = def.x;
for (let i = 0; i < 20; i++) { input = bt.controllers[1].read(bt, def); def.input(input.held, 0); def.update(); }
assert.equal(def.x, dummyX, 'Dummy holds position between attacks');
def.state = 'stand'; bt.damage(att, def, 100);
def.state = 'hit'; bt.damage(att, def, 100); bt.damage(att, def, 100);
assert.equal(bt.trainingStats.last, 88);
assert.equal(bt.trainingStats.damage, 288);
assert.equal(bt.trainingStats.hits, 3);
assert.equal(bt.trainingStats.best, 288);
def.state = 'stand'; bt.damage(att, def, 30);
assert.equal(bt.trainingStats.damage, 30, 'New sequence replaces previous combo');
assert.equal(bt.trainingStats.best, 288, 'Best survives a smaller combo');
bt.spawn({ x: 100 }); bt.freeze = { t: 30 }; bt.hitstop = 9;
tap('ArrowUp'); tap('Enter');
assert.equal(S.paused, false);
assert.equal(bt.phase, 'fight');
assert.equal(bt.round, 1);
assert.equal(bt.projectiles.length, 0);
assert.equal(bt.freeze, null);
assert.equal(bt.hitstop, 0);
assert.equal(bt.trainingGuard, 2);
assert.equal(bt.trainingStats.damage, 0);
assert.equal(bt.trainingStats.best, 288);
assert.equal(def.hp, def.maxHp);
assert.equal(att.meter, SM.METER_MAX);
assert.equal(att.x, SM.STAGE_W / 2 - 70);
console.log('training OK: menu, guard high/low/cross-up, stationary dummy, scaled damage, reset');
